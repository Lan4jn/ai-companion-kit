import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import http from 'node:http';
import vm from 'node:vm';
import { pathToFileURL } from 'node:url';

// Never import the production panel: all file-relative reads use this synthetic copy.
test('learning card reads aggregate insights without exposing model text', async (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'panel-learning-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.mkdirSync(path.join(root, 'scripts'));
  fs.cpSync(new URL('../src', import.meta.url), path.join(root, 'src'), { recursive: true });
  fs.copyFileSync(new URL('../scripts/panel.mjs', import.meta.url), path.join(root, 'scripts/panel.mjs'));
  fs.writeFileSync(path.join(root, 'package.json'), '{"type":"module"}');
  fs.mkdirSync(path.join(root, 'data'));
  const secret = 'SECRET_group_private_<img src=x onerror=alert(1)>';
  const insights = { lastLearnedAt: Date.now() - 60000, habits: [secret, secret], slangs: [{ term: secret, meaning: secret }], goldenSamples: [{ context: secret, reply: secret }], recentThoughts: [secret] };
  const file = path.join(root, 'data/human-insights.json');
  fs.writeFileSync(file, JSON.stringify(insights));
  const { handlePanelRequest } = await import(pathToFileURL(path.join(root, 'scripts/panel.mjs')));
  const server = http.createServer((req, res) => handlePanelRequest(req, res));
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => server.close());
  const base = `http://127.0.0.1:${server.address().port}/panel`;
  const snap = await (await fetch(base + '/api/snapshot')).json();
  assert.deepEqual(snap.lessons.counts, { habits: 2, slangs: 1, goldenSamples: 1, recentThoughts: 1 });
  assert.equal(snap.lessons.last, insights.lastLearnedAt);
  assert.equal(JSON.stringify(snap.lessons).includes(secret), false);
  const html = await (await fetch(base + '/')).text();
  assert.match(html, /human-insights/);
  const renderCode = html.match(/function renderLearn\(l\)\{[\s\S]*?\n\}/)?.[0];
  assert.ok(renderCode);
  const box = { innerHTML: '' };
  const context = vm.createContext({ el: () => box, esc: String, data: snap.lessons });
  vm.runInContext(renderCode + '\nrenderLearn(data)', context);
  assert.match(box.innerHTML, /聊天习惯 2/);
  assert.match(box.innerHTML, /接话样本 1/);
  assert.doesNotMatch(box.innerHTML, /SECRET/);
  fs.writeFileSync(file, JSON.stringify({ habits: 'invalid', slangs: null, goldenSamples: {}, recentThoughts: [], lastLearnedAt: Date.now() + 999999 }));
  const malformed = await (await fetch(base + '/api/snapshot')).json();
  assert.deepEqual(malformed.lessons.counts, { habits: 0, slangs: 0, goldenSamples: 0, recentThoughts: 0 });
  assert.equal(malformed.lessons.lastMin, null);
  fs.writeFileSync(file, '{broken');
  const broken = await (await fetch(base + '/api/snapshot')).json();
  assert.equal(broken.lessons.available, false);
  fs.unlinkSync(file);
  const missing = await (await fetch(base + '/api/snapshot')).json();
  assert.equal(missing.lessons.available, false);
});
