import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import http from 'node:http';
import {pathToFileURL} from 'node:url';
import {chromium} from 'playwright-core';

const root=path.resolve(import.meta.dirname,'..');
test('panel controls and chat use only isolated synthetic data', async t=>{
  const dir=fs.mkdtempSync(path.join(process.env.TMPDIR,'panel-controls-'));
  t.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
  fs.mkdirSync(path.join(dir,'scripts')); fs.mkdirSync(path.join(dir,'data/notebook'),{recursive:true});
  fs.cpSync(path.join(root,'scripts/panel.mjs'),path.join(dir,'scripts/panel.mjs'));
  fs.cpSync(path.join(root,'src'),path.join(dir,'src'),{recursive:true});
  fs.writeFileSync(path.join(dir,'package.json'),'{"type":"module"}');
  fs.writeFileSync(path.join(dir,'config.json'),JSON.stringify({ownerIds:['12345']}));
  fs.writeFileSync(path.join(dir,'data/chat-tail.jsonl'),JSON.stringify({dir:'in',text:'LEGACY_PRIVATE_SECRET'})+'\n');
  fs.writeFileSync(path.join(dir,'data/turns.jsonl'),JSON.stringify({where:'private:12345',text:'QQ_PRIVATE_SECRET',reply:'QQ_REPLY_SECRET'})+'\n');
  fs.writeFileSync(path.join(dir,'data/virtue.json'),JSON.stringify({axes:{'诚实':4},dayBudget:{}}));
  fs.writeFileSync(path.join(dir,'data/mbti.json'),JSON.stringify({version:3,code:'INFP',history:[]}));
  fs.writeFileSync(path.join(dir,'data/notebook/quoted"note.md'),'# synthetic note\nOnly fixture');
  const before=new Map(['uncaughtException','unhandledRejection','SIGTERM'].map(e=>[e,new Set(process.listeners(e))]));
  const {handlePanelRequest}=await import(pathToFileURL(path.join(dir,'scripts/panel.mjs')).href);
  for(const [event,listeners] of before) for(const listener of process.listeners(event)) if(!listeners.has(listener)) process.removeListener(event,listener);
  let calls=0, release;
  const brain={reply:async ({text})=>{calls++; if(text==='failure fixture') throw new Error('synthetic failure'); await new Promise(r=>release=r); return {text:'synthetic reply: '+text};}};
  const server=http.createServer((req,res)=>handlePanelRequest(req,res,{brain}));
  await new Promise(r=>server.listen(0,'127.0.0.1',r)); t.after(()=>server.close());
  const origin=`http://127.0.0.1:${server.address().port}`;
  const browser=await chromium.launch({executablePath:process.env.PANEL_TEST_CHROMIUM||'/root/.cache/ms-playwright/chromium-1217/chrome-linux64/chrome',headless:true,args:['--no-sandbox']}); t.after(()=>browser.close());
  const context=await browser.newContext({viewport:{width:1600,height:1100}});
  await context.route('**/*',route=>new URL(route.request().url()).origin===origin?route.continue():route.abort());
  const page=await context.newPage(); const errors=[]; const dialogs=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('dialog',d=>{dialogs.push(d.message()); d.accept();});
  await page.goto(origin+'/panel/');
  await page.locator('#chatInput').waitFor({timeout:60000});
  assert.doesNotMatch(await page.locator('#chat').innerText(),/LEGACY_PRIVATE_SECRET|QQ_PRIVATE_SECRET|QQ_REPLY_SECRET/);
  await page.locator('.nb-item').click();
  await page.getByText('Only fixture').waitFor();
  assert.equal(await page.locator('.nb-item').getAttribute('data-p'),'quoted"note.md');
  await page.locator('#chatToggle').click(); assert.equal(await page.locator('#chat').isVisible(),false);
  await page.locator('#chatToggle').click(); assert.equal(await page.locator('#chat').isVisible(),true);
  await page.locator('#chatInput').fill('fixture question'); await page.locator('#chatSendBtn').click();
  await page.waitForFunction(()=>document.querySelector('#chatSendBtn').disabled);
  await page.locator('#chatInput').fill('next draft'); await page.locator('#chatInput').press('Enter');
  await page.locator('#chatClear').click(); assert.equal(calls,1);
  release(); await page.getByText('synthetic reply: fixture question').waitFor();
  assert.equal(await page.locator('#chatInput').inputValue(),'next draft');
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir,'data/panel-chat-tail.jsonl'),'utf8').split('\n')[0]).text,'fixture question');
  await page.locator('#chatClear').click(); await page.getByText('还没有聊天记录').waitFor();
  assert.equal(fs.readFileSync(path.join(dir,'data/panel-chat-tail.jsonl'),'utf8'),'');
  await page.locator('#chatInput').fill('failure fixture'); await page.locator('#chatSendBtn').click();
  await page.waitForFunction(()=>document.querySelector('#chatInput').value==='' && !document.querySelector('#chatSendBtn').disabled);
  assert.equal(await page.getByText('failure fixture',{exact:true}).count(),0);
  assert.ok(dialogs.some(s=>s.includes('处理结果未知')));
  await page.evaluate(()=>{ window.prompt=()=>''; return editMood(3); });
  assert.ok(dialogs.some(s=>s.includes('0 到 6 的整数')));
  await page.evaluate(()=>{ window.prompt=()=> '2.5'; return editVirtue('诚实',0); });
  assert.ok(dialogs.some(s=>s.includes('之间的整数')));
  await page.evaluate(()=>editVirtueAt('诚实',{currentTarget:{getBoundingClientRect:()=>({left:0,width:100})},clientX:70}));
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir,'data/virtue.json'))).axes['诚实'],4);
  await page.locator('#rstVirtue').click(); await page.waitForFunction(()=>document.querySelector('#rstVirtue').textContent==='已归零');
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir,'data/virtue.json'))).axes['诚实'],0);
  await page.locator('#undoVirtue').click(); await page.waitForFunction(()=>document.querySelector('#undoVirtue').textContent==='已撤回');
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir,'data/virtue.json'))).axes['诚实'],4);
  await page.evaluate(()=>editMoodAt(5));
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir,'data/session_moods.json')))['private:12345'].panelTier,5);
  await page.locator('#rstMood').click(); await page.waitForFunction(()=>document.querySelector('#rstMood').textContent==='已清空');
  await page.locator('#undoMood').click(); await page.waitForFunction(()=>document.querySelector('#undoMood').textContent==='已撤回');
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir,'data/session_moods.json')))['private:12345'].panelTier,5);
  await page.locator('#rstMbti').click(); await page.waitForFunction(()=>document.querySelector('#rstMbti').textContent==='已重置');
  await page.locator('#undoMbti').click(); await page.waitForFunction(()=>document.querySelector('#undoMbti').textContent==='已撤回');
  if (!await page.locator('#tarotSw').isChecked()) await page.locator('label.sw i').click();
  await page.waitForFunction(()=>document.querySelector('#tarotSw').checked);
  await page.locator('label.sw i').click(); await page.waitForFunction(()=>document.querySelector('#tarotSwTxt').textContent==='关');
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir,'data/tarot.json'))).enabled,false);
  await page.locator('#tarotReroll').click(); await page.waitForFunction(()=>!document.querySelector('#tarotReroll').disabled);
  assert.ok(dialogs.some(s=>s.includes('先打开')));
  assert.deepEqual(errors,[]);
});
