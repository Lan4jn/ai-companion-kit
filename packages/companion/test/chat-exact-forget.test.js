import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {handleTurn} from '../src/index.js';
import {tiebaMessage} from './tieba-trusted-message-fixture.js';
import {initializeManagedStore,createManagedMemoryBrain} from '../src/memory-brain-trust.js';
import {startScopedSend} from '../src/chat-forget-coordination.js';

test('trusted owner can forget exactly a verified chat message through the real handler',async t=>{
 const dir=fs.mkdtempSync(path.join(process.env.TMPDIR,'chat-forget-')); t.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
 const directory=path.join(dir,'memory-brain-scoped'); initializeManagedStore(directory);
 const scope={tenant:'companion',platform:'qq',type:'private',session:'private:1',user:'1'};
 const opts={directory,scope,sources:['qq-private-message'],trustedProcess:true,backend:'sqlite-fts'};
 const store=createManagedMemoryBrain(opts);
 await store.remember(scope,{text:'合成苹果',source:'qq-private-message',evidence:'onebot-message:123'});
 await store.remember(scope,{text:'合成梨子',source:'qq-private-message',evidence:'onebot-message:124'});
 const sent=[]; const deps={bot:{send:async(_k,s)=>{sent.push(s);return {ok:true}}},memory:{dir},brain:{},human:{},waker:{}};
 const cfg={ownerIds:['1'],dataDir:dir,memoryBrain:{enabled:true,backend:'sqlite-fts',trustedProcess:true,trustedScope:scope,authorizedSources:['qq-private-message']}};
 await handleTurn(deps,[await tiebaMessage({text:'忘记这条聊天记忆：消息ID 123',id:500})],cfg);
 assert.match(sent.join(''),/QQ私聊.*消息ID.*备份/);
 assert.equal(sent.length,1);
 assert.ok([...sent.join('')].length<=50, 'receipt must fit the per-turn budget');
 assert.equal((await store.privateHistory(scope)).some(x=>x.evidence==='onebot-message:123'),false);
 assert.equal((await store.privateHistory(scope)).some(x=>x.evidence==='onebot-message:124'),true);
 const run=async(text,userId=1,type='private',config=cfg)=>{sent.length=0; await handleTurn(deps,[await tiebaMessage({text,userId,type,groupId:type==='group'?9:undefined,id:501})],config); return sent.join('');};
 assert.match(await run('忘了吧'),/哪一条.*消息ID/);
 assert.match(await run('不用记'),/哪一条/);
 assert.match(await run('忘记这条聊天记忆：消息ID 124',2),/没有删除/);
 assert.match(await run('忘记这条聊天记忆：消息ID 124',1,'group'),/没有删除/);
 sent.length=0;
 const genuine=await tiebaMessage({text:'忘记这条聊天记忆：消息ID 124',id:502});
 await handleTurn(deps,[{...genuine}],cfg);
 assert.match(sent.join(''),/没有删除/);
 sent.length=0;
 await handleTurn(deps,[genuine,await tiebaMessage({text:'另一条消息',id:503})],cfg);
 assert.match(sent.join(''),/没有删除/);
 assert.match(await run('忘记这条聊天记忆：消息ID 999'),/没有找到/);
 assert.match(await run('忘记这条聊天记忆：消息ID 124',1,'private',{...cfg,durableChat:{enabled:true}}),/无法安全遗忘/);
 await store.commitChatHistory(scope,{turnId:'merged',events:['onebot-message:125','onebot-message:126'],text:'合成合并',reply:'合成回复'});
 assert.match(await run('忘记这条聊天记忆：消息ID 125'),/合并/);
 const manager=createManagedMemoryBrain({...opts,management:true});
 await assert.rejects(manager.forget({context:scope,source:'qq-private-message',evidence:'onebot-message:999',exactSingle:true}));
 await assert.rejects(manager.forget({context:scope,source:'qq-private-message',evidence:'onebot-message:125',exactSingle:true}));
 assert.equal((await store.chatHistory(scope)).length,1);
 let release,ready; const gate=new Promise(r=>release=r), started=new Promise(r=>ready=r);
 const active=startScopedSend(directory,scope,'qq-private-message',()=>true,async()=>{ready();await gate}); await started;
 try { assert.match(await run('忘记这条聊天记忆：消息ID 124'),/超时|无法确认/); } finally {release();await active;}
 assert.equal((await store.privateHistory(scope)).some(x=>x.evidence==='onebot-message:124'),true);
 assert.match(await run('忘记这条聊天记忆：消息ID 124',1,'private',{...cfg,memoryBrain:{...cfg.memoryBrain,python:'/nonexistent'}}),/失败|无法确认/);
});
