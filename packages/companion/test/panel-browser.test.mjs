import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import http from 'node:http';
import {pathToFileURL} from 'node:url';
import {chromium} from 'playwright-core';

const root = path.resolve(import.meta.dirname, '..');
const executablePath = process.env.PANEL_TEST_CHROMIUM || '/root/.cache/ms-playwright/chromium-1217/chrome-linux64/chrome';

test('isolated browser: search, unblock, drag, help and PNG export', async t => {
  const dir = fs.mkdtempSync(path.join(process.env.TMPDIR, 'panel-browser-'));
  t.after(() => fs.rmSync(dir, {recursive:true, force:true}));
  fs.mkdirSync(path.join(dir,'scripts'));
  fs.cpSync(path.join(root,'scripts/panel.mjs'),path.join(dir,'scripts/panel.mjs'));
  fs.cpSync(path.join(root,'src'),path.join(dir,'src'),{recursive:true});
  fs.writeFileSync(path.join(dir,'package.json'),'{"type":"module"}');
  fs.mkdirSync(path.join(dir,'data'));
  fs.writeFileSync(path.join(dir,'data/virtue.json'), JSON.stringify({version:2,axes:{'诚实':4},dayBudget:{}}));
  fs.writeFileSync(path.join(dir,'data/people.json'), JSON.stringify({'55555':{name:'Synthetic Person',dialogues:12}}));
  fs.writeFileSync(path.join(dir,'data/respect.json'), JSON.stringify({users:{'55555':{name:'Synthetic Person',strikes:5,disliked:true}}}));
  const before = new Map(['uncaughtException','unhandledRejection','SIGTERM'].map(e=>[e,new Set(process.listeners(e))]));
  const {handlePanelRequest} = await import(pathToFileURL(path.join(dir,'scripts/panel.mjs')).href);
  for(const [event, listeners] of before) for(const listener of process.listeners(event)) if(!listeners.has(listener)) process.removeListener(event,listener);
  const {createRespectGuard} = await import(pathToFileURL(path.join(dir,'src/respect-guard.js')).href);
  const guard=createRespectGuard({file:path.join(dir,'data/respect.json')});
  const server=http.createServer((req,res)=>handlePanelRequest(req,res,{respectGuard:guard}));
  await new Promise(r=>server.listen(0,'127.0.0.1',r));
  t.after(()=>server.close());
  const port=server.address().port;
  const browser=await chromium.launch({executablePath,headless:true,args:['--no-sandbox']});
  t.after(()=>browser.close());
  const context=await browser.newContext({acceptDownloads:true,viewport:{width:1600,height:1100}});
  await context.route('**/*', route => new URL(route.request().url()).origin === `http://127.0.0.1:${port}` ? route.continue() : route.abort());
  const page=await context.newPage();
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  page.on('dialog',dialog=>dialog.accept());
  await page.goto(`http://127.0.0.1:${port}/panel/`);
  await page.locator('#relRosterList option').first().waitFor({state:'attached'});
  assert.equal(await page.locator('#tarotRules').count(),1);
  await page.locator('#tarotHelp').click();
  assert.equal(await page.locator('#tarotRules').isVisible(),true);
  await page.locator('#relSearch').fill('Synthetic Person');
  await page.locator('#relDetail').getByText('Synthetic Person').waitFor();
  await page.locator('.rel-unblock-btn').click();
  await page.waitForFunction(() => !document.querySelector('.rel-unblock-btn'));
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir,'data/respect.json'))).users['55555'].disliked,false);
  assert.equal(guard.handleIncoming({userId:'55555'}).blocked,false);
  const initial=await page.evaluate(()=>{const n=REL_DATA.nodes.find(n=>n.id==='55555'); const r=el('relCanvas').getBoundingClientRect(); return {x:n.x,y:n.y,left:r.left,top:r.top};});
  await page.locator('#relCanvas').scrollIntoViewIfNeeded();
  const pos=await page.evaluate(()=>{const n=REL_DATA.nodes.find(n=>n.id==='55555'); const r=el('relCanvas').getBoundingClientRect(); return {x:n.x,y:n.y,left:r.left,top:r.top};});
  await page.mouse.move(pos.left+pos.x,pos.top+pos.y); await page.mouse.down();
  await page.mouse.move(pos.left+pos.x+35,pos.top+pos.y+25,{steps:5}); await page.mouse.up();
  const after=await page.evaluate(()=>{const n=REL_DATA.nodes.find(n=>n.id==='55555'); return {x:n.x,y:n.y};});
  assert.ok(Math.abs(after.x-initial.x-35)<3 && Math.abs(after.y-initial.y-25)<3);
  const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#png').click()]);
  const bytes=fs.readFileSync(await download.path());
  assert.deepEqual([...bytes.subarray(0,8)],[137,80,78,71,13,10,26,10]);
  assert.equal(bytes.readUInt32BE(16),1080); assert.equal(bytes.readUInt32BE(20),1080);
  const coloredPixels=await page.evaluate(async base64=>{
    const image=new Image(); image.src='data:image/png;base64,'+base64; await image.decode();
    const canvas=document.createElement('canvas'); canvas.width=1080; canvas.height=1080;
    const ctx=canvas.getContext('2d'); ctx.drawImage(image,0,0);
    const data=ctx.getImageData(300,350,480,400).data;
    let count=0; for(let i=0;i<data.length;i+=4) if(data[i]!==13 || data[i+1]!==17 || data[i+2]!==23) count++;
    return count;
  },bytes.toString('base64'));
  assert.ok(coloredPixels>1000,'radar must be rendered even when the optional avatar is unavailable');
  assert.deepEqual(errors,[]);
});
